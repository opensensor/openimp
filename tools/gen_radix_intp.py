#!/usr/bin/env python3
"""Generate src/t30/radix/t30_radix_intp.h from the GPL-2.0 T30 kernel header
drivers/video/soc_vpu/radix/radix.h (radix_IntpFMT[], HEVC_RADIX_QPEL and
HEVC_RADIX_EPEL, the motion compensation interpolation formats).

usage: gen_radix_intp.py <linux>/drivers/video/soc_vpu/radix/radix.h > t30_radix_intp.h
"""
import re
import sys

src = open(sys.argv[1]).read()
defs = {m.group(1): int(m.group(2), 0)
        for m in re.finditer(r'#define\s+(RADIX_\w+)\s+(-?(?:0x)?[0-9a-fA-F]+)\s', src)}
for name, val in (('RADIX_TAP2', 0), ('RADIX_TAP4', 1), ('RADIX_TAP6', 2), ('RADIX_TAP8', 3),
                  ('RADIX_HPEL', 0), ('RADIX_QPEL', 1), ('RADIX_EPEL', 2)):
    defs[name] = val
body = src[src.index('radix_IntpFMT[][16] = {'):]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
toks = re.findall(r'[{}]|-?\w+', body.split('=', 1)[1])

def parse(i):
    """returns (nested list, next index) for the brace group at toks[i]"""
    assert toks[i] == '{'
    out, i = [], i + 1
    while toks[i] != '}':
        if toks[i] == '{':
            sub, i = parse(i)
            out.append(sub)
        else:
            t = toks[i]
            out.append(defs[t] if t in defs else int(t, 0))
            i += 1
    return out, i + 1

table, _ = parse(0)
# field shapes of radix_IntpFMT_t (radix.h): 35 bytes
shape = [1, 2, 1, 1, 2, 2, (2, 8), 2, 2, 2, 2, 2]

def flat(entry):
    out = []
    for val, sh in zip(entry + [[]] * (len(shape) - len(entry)), shape):
        if sh == 1:
            out.append(val if isinstance(val, int) else 0)
        elif isinstance(sh, tuple):
            rows = val if isinstance(val, list) else []
            for r in range(sh[0]):
                row = rows[r] if r < len(rows) and isinstance(rows[r], list) else []
                out += (row + [0] * sh[1])[:sh[1]]
        else:
            v = val if isinstance(val, list) else []
            out += (v + [0] * sh)[:sh]
    assert len(out) == 35
    return out

names = {15: 'T30_RADIX_INTP_HEVC_QPEL', 16: 'T30_RADIX_INTP_HEVC_EPEL'}
print('/* SPDX-License-Identifier: GPL-2.0 */')
print('/* Generated by tools/gen_radix_intp.py from the T30 kernel header')
print(' * drivers/video/soc_vpu/radix/radix.h (radix_IntpFMT, GPL-2.0, Ingenic).')
print(' * Each entry is radix_IntpFMT_t: tap, intp_pkg[2], hldgl, avsdgl, intp[2],')
print(' * intp_dir[2], intp_coef[2][8], intp_rnd[2], intp_sft[2], intp_sintp[2],')
print(' * intp_srnd[2], intp_sbias[2] (35 bytes). */')
print('#ifndef T30_RADIX_INTP_H')
print('#define T30_RADIX_INTP_H')
print('#include <stdint.h>')
for idx, name in names.items():
    print(f'static const int8_t {name}[16][35] = {{')
    for e in table[idx]:
        print('    {' + ', '.join(str(v) for v in flat(e)) + '},')
    print('};')
print('#endif')

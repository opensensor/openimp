#!/usr/bin/env python3
"""Generate at_isp_rt.c: same-value Get -> Set -> Get round trips for every IMP_ISP_*Get<X>/Set<X> pair of the vendor
headers that takes exactly one struct pointer (plus IMPVI_NUM on T40/T41) and that the hand-written at_isp.c does not
already round-trip.  Type-agnostic: a 16 KB guarded buffer holds the struct, the second Get must read back the same bytes.
Usage: gen_rt.py > at_isp_rt.c   (HDR = vendor SDK include root)"""
import glob, os, re, sys
HDR = os.environ.get("HDR") or sys.exit("set HDR=<vendor SDK include root>")
HERE = os.path.dirname(os.path.abspath(__file__))
SETS = [("T10", "T10/3.12.0/zh"), ("T20", "T20/3.12.0/zh"), ("T21", "T21/1.0.33/zh"), ("T23", "T23/1.3.0/zh"), ("T31", "T31/1.1.6/en"),
        ("T40", "T40/1.3.1/en"), ("T41", "T41/1.2.6/en")]
COND = {"T40": "defined(APITEST_T40)", "T41": "(defined(PLATFORM_T41) && !defined(APITEST_T40))"}
# never round-tripped: hangs/oopses seen, hardware writes, mode switches, things that are not plain configuration
SKIP = re.compile(r"AeExpList|SensorRegister|Reg|Bin|GPIO|Process|Freeze|Raw|Mask|Draw|OSD|Osd|HVFlip|HVFLIP|Hflip|Vflip|"
                  r"CustomMode|Bypass|Module|Wdr|WDR|FaceAe|FaceAwb|FrameDrop|VideoDrop|Alarm|Sensor|_Sec|CameraInput|StreamOut|Switch|"
                  r"RunningMode|AutoZoom|FrontCrop|WB$|Defog|Movestate|AeAlgo|AwbAlgo|Scaler|Ldc|LDC|DPC|Dpc|Hldc|HLDC|Expr|AeAttr|IntegrationTime|AwbAttr|AeScenceAttr|^WB|CCM|Csc|Gamma|Bcsh|Brightness|Contrast|Saturation|Sharpness|Sinter|Temper")
mine = open(os.path.join(HERE, "at_isp.c")).read()
pairs = {}
for soc, s in SETS:
    for h in glob.glob("%s/%s/imp/imp_isp.h" % (HDR, s)):
        t = open(h, errors="replace").read()
        t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
        for m in re.finditer(r"\bint(?:32_t)?\s+(IMP_ISP_(?:Tuning_)?)(Get|Set)(\w+)\s*\(([^)]*)\)\s*;", t):
            pre, gs, name, args = m.groups()
            a = [x.strip() for x in args.split(",") if x.strip()]
            if a and a[0].startswith("IMPVI_NUM"):
                a = a[1:]
            if len(a) != 1 or "*" not in a[0]:
                continue
            pairs.setdefault((pre, name), {}).setdefault(soc, set()).add(gs)
out = ["/* generated by gen_rt.py - do not edit.  Same-value round trips of ISP Get/Set pairs (readback equal). */",
       '#include <unistd.h>', '#include "apitest.h"', "",
       "#if defined(PLATFORM_T41)", "typedef int (*rt_fn)(IMPVI_NUM, void *);", "# define RTV IMPVI_MAIN,",
       "#else", "typedef int (*rt_fn)(void *);", "# define RTV", "#endif", "",
       "#define RTBUF 16384",
       "#define ISPRT(G, S, label) do { \\",
       "    if (!(G) || !(S)) { rep_na(FN(S)); break; } \\",
       "    unsigned char *a_ = gnew(RTBUF), *b_ = gnew(RTBUF); \\",
       "    int r1_ = ((rt_fn)(void *)G)(RTV a_); gchk(a_); \\",
       "    if (r1_ != 0) { rep(FN(G), r1_, V_FAIL, \"%s: get failed\", label); gfree(a_); gfree(b_); break; } \\",
       "    int r2_ = ((rt_fn)(void *)S)(RTV a_); \\",
       "    int r3_ = ((rt_fn)(void *)G)(RTV b_); gchk(b_); \\",
       "    rep(FN(G), r1_, V_PASS, \"%s: read\", label); \\",
       "    rep(FN(S), r2_, (r2_ == 0 && r3_ == 0 && !memcmp(a_, b_, RTBUF)) ? V_PASS : V_FAIL, \\",
       "        \"%s: same value written (set ret %d), read back %s\", label, r2_, (r3_ == 0 && !memcmp(a_, b_, RTBUF)) ? \"equal\" : \"DIFFERENT\"); \\",
       "    gfree(a_); gfree(b_); } while (0)", "", "void t_isp_rt(void)", "{", '    rep_area("isp-rt");']
n = 0
for (pre, name), gs in sorted(pairs.items()):
    socs = [x for x, v in gs.items() if v == {"Get", "Set"}]
    if not socs or SKIP.search(name):
        continue
    g, s = "IMP_ISP_%sGet%s" % (pre[8:], name), "IMP_ISP_%sSet%s" % (pre[8:], name)
    if g in mine and s in mine:
        continue
    cond = " || ".join(COND.get(x, "defined(PLATFORM_%s)" % x) for x in sorted(socs))
    out += ["#if (%s) && HAS_%s && HAS_%s" % (cond, g, s), "    ISPRT(%s, %s, \"%s\");" % (g, s, name), "#endif"]
    n += 1
out += ["}", ""]
print("\n".join(out))
print("pairs: %d" % n, file=sys.stderr)

typedef struct { int decType; uint32_t maxWidth, maxHeight; int pixelFormat; uint32_t nrKeepStream, frmRateNum, frmRateDen; } attr_t;
typedef struct { int i_payload; uint8_t *p_payload; int64_t timeStamp; } stream_t;

int IMP_Decoder_CreateChn(int, const attr_t *);
int IMP_Decoder_DestroyChn(int);
int IMP_Decoder_StartRecvPic(int);
int IMP_Decoder_StopRecvPic(int);
int IMP_Decoder_SendStreamTimeout(int, stream_t *, uint32_t);
int IMP_Decoder_PollingFrame(int, uint32_t);
int IMP_Decoder_GetFrame(int, IMPFrameInfo **);
int IMP_Decoder_ReleaseFrame(int, IMPFrameInfo *);


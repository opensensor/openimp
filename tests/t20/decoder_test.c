/* the logger is not linked in this test */
int openimp_log_level = 0;
void imp_log_emit(int prio, const char *tag, const char *fmt, ...) { (void)prio; (void)tag; (void)fmt; }

static int fails;
#define CHECK(c, ...) do { if (!(c)) { fails++; printf("FAIL line %d: ", __LINE__); printf(__VA_ARGS__); printf("\n"); } } while (0)

static long ms_since(const struct timespec *t0)
{
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (t.tv_sec - t0->tv_sec) * 1000 + (t.tv_nsec - t0->tv_nsec) / 1000000;
}

int main(void)
{
    attr_t a = { PT_JPEG, 64, 64, 10 /* NV12 */, 2, 25, 1 }, bad;
    stream_t st = { (int)sizeof(dec_jpg), (uint8_t *)dec_jpg, 4242 }, junk;
    uint8_t junkbuf[64];
    IMPFrameInfo *f1 = NULL, *f2 = NULL, *f3 = NULL;
    struct timespec t0;
    const uint8_t *pic;
    long yl = 0, yr = 0;

    mallopt(M_MMAP_MAX, 0);         /* keep pictures below 4 GiB (32-bit address word) */
    memset(junkbuf, 0x5a, sizeof(junkbuf));
    junk.i_payload = sizeof(junkbuf); junk.p_payload = junkbuf; junk.timeStamp = 1;

    /* nothing works before CreateChn */
    CHECK(IMP_Decoder_StartRecvPic(0) == -1, "StartRecvPic before create");
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 50) == -1, "Send before create");
    CHECK(IMP_Decoder_PollingFrame(0, 10) == -1, "Polling before create");
    CHECK(IMP_Decoder_DestroyChn(0) == -1, "Destroy before create");

    /* CreateChn argument checks */
    bad = a; bad.decType = PT_H264;
    CHECK(IMP_Decoder_CreateChn(0, &bad) == -1, "H.264 refused");
    bad = a; bad.pixelFormat = 17 /* BGRA */;
    CHECK(IMP_Decoder_CreateChn(0, &bad) == -1, "BGRA refused");
    bad = a; bad.maxWidth = 0;
    CHECK(IMP_Decoder_CreateChn(0, &bad) == -1, "zero size refused");
    CHECK(IMP_Decoder_CreateChn(1, &a) == -1, "channel 1 refused");
    CHECK(IMP_Decoder_CreateChn(0, NULL) == -1, "NULL attr refused");
    CHECK(IMP_Decoder_CreateChn(0, &a) == 0, "create");
    CHECK(IMP_Decoder_CreateChn(0, &a) == -1, "second create refused");
    CHECK(IMP_Decoder_StartRecvPic(0) == 0, "start");

    /* nothing decoded yet */
    clock_gettime(CLOCK_MONOTONIC, &t0);
    CHECK(IMP_Decoder_PollingFrame(0, 100) == -1, "polling times out");
    CHECK(ms_since(&t0) >= 90, "polling waited %ld ms", ms_since(&t0));
    CHECK(IMP_Decoder_GetFrame(0, &f1) == -1, "GetFrame without picture");

    /* junk and oversized pictures are refused, the channel keeps working */
    CHECK(IMP_Decoder_SendStreamTimeout(0, &junk, 100) == -1, "junk refused");
    junk.i_payload = 0;
    CHECK(IMP_Decoder_SendStreamTimeout(0, &junk, 100) == -1, "empty refused");

    /* two pictures in flight, third waits for a release (nrKeepStream = 2) */
    st.timeStamp = 1000;
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 500) == 0, "send 1");
    st.timeStamp = 2000;
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 500) == 0, "send 2");
    clock_gettime(CLOCK_MONOTONIC, &t0);
    st.timeStamp = 3000;
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 150) == -1, "send 3 blocked");
    CHECK(ms_since(&t0) >= 140, "send 3 waited %ld ms", ms_since(&t0));
    CHECK(IMP_Decoder_PollingFrame(0, 100) == 0, "polling");
    CHECK(IMP_Decoder_GetFrame(0, &f1) == 0 && f1, "get 1");
    CHECK(IMP_Decoder_GetFrame(0, &f2) == 0 && f2 && f2 != f1, "get 2");
    CHECK(IMP_Decoder_GetFrame(0, &f3) == -1, "get 3 (none left)");
    CHECK(f1->timeStamp == 1000 && f2->timeStamp == 2000, "FIFO order %lld %lld", (long long)f1->timeStamp, (long long)f2->timeStamp);
    CHECK(f1->width == 32 && f1->height == 24 && f1->pixfmt == 10 && f1->size == 32 * 24 * 3 / 2,
          "frame geometry %ux%u fmt %d size %u", f1->width, f1->height, f1->pixfmt, f1->size);

    /* picture content: left half yellow (Y 208, Cb 33, Cr 143), right half blue (Y 70, Cb 201, Cr 107) */
    pic = (const uint8_t *)(uintptr_t)f1->virAddr;
    for (int j = 0; j < 24; j++)
        for (int i = 0; i < 16; i++) { yl += pic[j * 32 + i]; yr += pic[j * 32 + 16 + i]; }
    yl /= 16 * 24; yr /= 16 * 24;
    CHECK(labs(yl - 208) < 8 && labs(yr - 70) < 8, "Y %ld %ld", yl, yr);
    CHECK(abs(pic[768] - 33) < 8 && abs(pic[769] - 143) < 8 && abs(pic[768 + 16] - 201) < 8 && abs(pic[768 + 17] - 107) < 8,
          "CbCr %d %d / %d %d", pic[768], pic[769], pic[784], pic[785]);

    /* release: invalid pointer, then both, a slot frees up for a new picture */
    CHECK(IMP_Decoder_ReleaseFrame(0, (IMPFrameInfo *)&st) == -1, "foreign pointer");
    CHECK(IMP_Decoder_ReleaseFrame(0, f1) == 0, "release 1");
    CHECK(IMP_Decoder_ReleaseFrame(0, f1) == -1, "double release");
    st.timeStamp = 3000;
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 500) == 0, "send 3 after release");
    CHECK(IMP_Decoder_ReleaseFrame(0, f2) == 0, "release 2");
    CHECK(IMP_Decoder_GetFrame(0, &f3) == 0 && f3->timeStamp == 3000, "get 3");
    CHECK(IMP_Decoder_ReleaseFrame(0, f3) == 0, "release 3");

    /* StopRecvPic, DestroyChn */
    CHECK(IMP_Decoder_StopRecvPic(0) == 0, "stop");
    CHECK(IMP_Decoder_DestroyChn(0) == 0, "destroy");
    CHECK(IMP_Decoder_DestroyChn(0) == -1, "second destroy");

    /* maxWidth smaller than the picture, YUV420P and NV21 outputs */
    bad = a; bad.maxWidth = 16;
    CHECK(IMP_Decoder_CreateChn(0, &bad) == 0, "create small");
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 200) == -1, "picture above maxWidth refused");
    CHECK(IMP_Decoder_DestroyChn(0) == 0, "destroy small");
    for (int k = 0; k < 2; k++) {
        bad = a; bad.pixelFormat = k ? 11 : 0; bad.nrKeepStream = 0;
        CHECK(IMP_Decoder_CreateChn(0, &bad) == 0, "create fmt %d", bad.pixelFormat);
        CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 500) == 0, "send fmt %d", bad.pixelFormat);
        CHECK(IMP_Decoder_GetFrame(0, &f1) == 0, "get fmt %d", bad.pixelFormat);
        pic = (const uint8_t *)(uintptr_t)f1->virAddr;
        if (k) CHECK(abs(pic[768] - 143) < 8 && abs(pic[769] - 33) < 8, "NV21 VU %d %d", pic[768], pic[769]);
        else   CHECK(abs(pic[768] - 33) < 8 && abs(pic[768 + 192] - 143) < 8, "I420 U/V planes %d %d", pic[768], pic[768 + 192]);
        CHECK(IMP_Decoder_ReleaseFrame(0, f1) == 0, "release fmt %d", bad.pixelFormat);
        CHECK(IMP_Decoder_DestroyChn(0) == 0, "destroy fmt %d", bad.pixelFormat);
    }

    /* destroy with a picture still held and one waiting */
    CHECK(IMP_Decoder_CreateChn(0, &a) == 0, "create again");
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 500) == 0, "send");
    CHECK(IMP_Decoder_SendStreamTimeout(0, &st, 500) == 0, "send");
    CHECK(IMP_Decoder_GetFrame(0, &f1) == 0, "get");
    CHECK(IMP_Decoder_DestroyChn(0) == 0, "destroy with held frame");
    CHECK(IMP_Decoder_ReleaseFrame(0, f1) == -1, "release after destroy");

    if (fails) { printf("decoder_test: %d FAILED\n", fails); return 1; }
    puts("decoder_test: ok");
    return 0;
}

/* Host test of IMP_Decoder_* on T10/T20/T21 (software JPEG decoder, OPENIMP_DECODER_SW_ONLY):
 * the channel API as the vendor libimp 1.0.33 / 3.12.0 documents it - channel 0 only, JPEG into
 * YUV420P / NV12 / NV21, nrKeepStream pictures in flight, PollingFrame / GetFrame / ReleaseFrame,
 * refusal of other payloads / formats / oversized pictures / junk.  Built without PIE: the frame
 * struct carries the picture address as a 32-bit word, as on MIPS. */

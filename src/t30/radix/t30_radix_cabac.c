/* H.265 9.3.2.2: initValue and QP -> (pStateIdx << 1) | valMps */
static uint8_t ctx_state(int qp, int v)
{
    int slope = (v >> 4) * 5 - 45, offset = ((v & 15) << 3) - 16;
    int s = ((slope * qp) >> 4) + offset;

    if (s > 125)
        return 125;             /* initState 126 */
    if (s < 1)
        s = 1;
    return s < 64 ? (uint8_t)((63 - s) << 1) : (uint8_t)(((s - 64) << 1) | 1);
}

void t30_radix_cabac_init(uint8_t state[T30_RADIX_CABAC_CONTEXTS],
                          int slice_type, int qp)
{
    qp = qp < 0 ? 0 : qp > 51 ? 51 : qp;
    for (unsigned g = 0; g < sizeof(groups) / sizeof(groups[0]); g++)
        for (unsigned i = 0; i < groups[g].count; i++)
            state[groups[g].first + i] =
                ctx_state(qp, groups[g].init[slice_type * groups[g].count + i]);
}

/*
 * NV12 rotation for the T31 FrameSource: plain C, plus an MXU2 path.
 *
 * 90/270: the source is walked in 32x32 tiles (the vendor block size), so a
 * tile's 32 source and 32 destination lines stay in the 32 KB L1 D-cache.
 * Inside a tile, 4x4 luma blocks (2x2 for CbCr pairs) are loaded as one
 * 32-bit word per row, transposed in registers and stored as one word per
 * destination row: one load and one store per 4 luma samples.
 * 180: each row is copied to the mirrored row with the words reversed.
 * Edges that do not fill a word, and unaligned buffers, take the scalar
 * path.
 *
 * MXU2 (T10/T20/T31 parts that grant it to user processes, see
 * core/openimp_mxu2.h): 16x16 luma / 8x8 CbCr-pair blocks are transposed
 * in vector registers (16 loads, 64 SHUFV, 16 stores per 256 pixels;
 * generated by tools/gen_nv12_rotate_mxu2.py), 180 degrees reverses 16
 * bytes per SHUFV. The strips that do not fill a block go through the C
 * code above. Used only after a bit-exact selftest against the C path on
 * the running CPU; OPENIMP_MXU=0 keeps C.
 */
#include "nv12_rotate.h"

#include <stddef.h>
#include <string.h>

#include "core/openimp_mxu2.h"
#include "framesource/nv12_rotate_mxu2_gen.h"

typedef uint32_t nv12_rot_u32 __attribute__((may_alias));

#define NV12_ROT_TILE 32u

#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__
#define NV12_ROT_WORDS 1
#else
#define NV12_ROT_WORDS 0
#endif

int nv12_rotate_out_dims(int mode, uint32_t width, uint32_t height,
                         uint32_t *out_width, uint32_t *out_height)
{
    switch (mode) {
    case NV12_ROT_NONE:
    case NV12_ROT_180:
        *out_width = width;
        *out_height = height;
        return 0;
    case NV12_ROT_90_CCW:
    case NV12_ROT_90_CW:
        *out_width = height;
        *out_height = width;
        return 0;
    default:
        return -1;
    }
}

/* Destination coordinates of source sample (x, y). */
static inline void rot_map(int mode, uint32_t w, uint32_t h, uint32_t x,
                           uint32_t y, uint32_t *dx, uint32_t *dy)
{
    switch (mode) {
    case NV12_ROT_90_CW:
        *dx = h - 1u - y;
        *dy = x;
        break;
    case NV12_ROT_90_CCW:
        *dx = y;
        *dy = w - 1u - x;
        break;
    case NV12_ROT_180:
        *dx = w - 1u - x;
        *dy = h - 1u - y;
        break;
    default:
        *dx = x;
        *dy = y;
        break;
    }
}

/* Scalar rotation of the rectangle [x0,x1) x [y0,y1) of the plane. */
static void rot_scalar(const uint8_t *src, uint32_t ss, uint8_t *dst,
                       uint32_t ds, uint32_t w, uint32_t h, int bpp,
                       int mode, uint32_t x0, uint32_t x1, uint32_t y0,
                       uint32_t y1)
{
    uint32_t x, y, dx, dy;

    for (y = y0; y < y1; y++) {
        const uint8_t *s = src + (size_t)y * ss;

        for (x = x0; x < x1; x++) {
            rot_map(mode, w, h, x, y, &dx, &dy);
            if (bpp == 1) {
                dst[(size_t)dy * ds + dx] = s[x];
            } else {
                uint8_t *d = dst + (size_t)dy * ds + (size_t)dx * 2u;

                d[0] = s[x * 2u];
                d[1] = s[x * 2u + 1u];
            }
        }
    }
}

#if NV12_ROT_WORDS
#define LD32(p)     (*(const nv12_rot_u32 *)(const void *)(p))
#define ST32(p, v)  (*(nv12_rot_u32 *)(void *)(p) = (v))

/* 4x4 byte transpose: a..d are four rows (byte k = column k); on return
 * c0..c3 are the four columns (byte k = row k: a, b, c, d). */
#define TRANSPOSE4(a, b, c, d, c0, c1, c2, c3) do {                     \
        uint32_t t0_ = ((a) & 0x00ff00ffu) | (((b) & 0x00ff00ffu) << 8); \
        uint32_t t1_ = (((a) >> 8) & 0x00ff00ffu) | ((b) & 0xff00ff00u); \
        uint32_t t2_ = ((c) & 0x00ff00ffu) | (((d) & 0x00ff00ffu) << 8); \
        uint32_t t3_ = (((c) >> 8) & 0x00ff00ffu) | ((d) & 0xff00ff00u); \
        (c0) = (t0_ & 0xffffu) | (t2_ << 16);                           \
        (c1) = (t1_ & 0xffffu) | (t3_ << 16);                           \
        (c2) = (t0_ >> 16) | (t2_ & 0xffff0000u);                       \
        (c3) = (t1_ >> 16) | (t3_ & 0xffff0000u);                       \
    } while (0)

/* Luma 90/270, x and y ranges multiples of 4. */
static void rot90_y_words(const uint8_t *src, uint32_t ss, uint8_t *dst,
                          uint32_t ds, uint32_t w, uint32_t h, int mode,
                          uint32_t x0, uint32_t x1, uint32_t y0, uint32_t y1)
{
    uint32_t x, y;

    for (y = y0; y < y1; y += 4u) {
        const uint8_t *s0 = src + (size_t)y * ss;
        const uint8_t *s1 = s0 + ss;
        const uint8_t *s2 = s1 + ss;
        const uint8_t *s3 = s2 + ss;

        for (x = x0; x < x1; x += 4u) {
            uint32_t r0 = LD32(s0 + x), r1 = LD32(s1 + x);
            uint32_t r2 = LD32(s2 + x), r3 = LD32(s3 + x);
            uint32_t c0, c1, c2, c3;
            uint8_t *d;

            if (mode == NV12_ROT_90_CW) {
                /* dst row x+j, columns h-4-y .. h-1-y hold rows y+3 .. y */
                TRANSPOSE4(r3, r2, r1, r0, c0, c1, c2, c3);
                d = dst + (size_t)x * ds + (h - 4u - y);
                ST32(d, c0);
                ST32(d + ds, c1);
                ST32(d + 2u * ds, c2);
                ST32(d + 3u * ds, c3);
            } else {
                /* dst row w-1-x-j, columns y .. y+3 hold rows y .. y+3 */
                TRANSPOSE4(r0, r1, r2, r3, c0, c1, c2, c3);
                d = dst + (size_t)(w - 1u - x) * ds + y;
                ST32(d, c0);
                ST32(d - ds, c1);
                ST32(d - 2u * ds, c2);
                ST32(d - 3u * ds, c3);
            }
        }
    }
}

/* CbCr pairs 90/270, x and y ranges multiples of 2 (in pairs). */
static void rot90_uv_words(const uint8_t *src, uint32_t ss, uint8_t *dst,
                           uint32_t ds, uint32_t w, uint32_t h, int mode,
                           uint32_t x0, uint32_t x1, uint32_t y0, uint32_t y1)
{
    uint32_t x, y;

    for (y = y0; y < y1; y += 2u) {
        const uint8_t *s0 = src + (size_t)y * ss;
        const uint8_t *s1 = s0 + ss;

        for (x = x0; x < x1; x += 2u) {
            uint32_t a = LD32(s0 + x * 2u), b = LD32(s1 + x * 2u);
            uint8_t *d;

            if (mode == NV12_ROT_90_CW) {
                /* dst row x+j, pair columns h-2-y, h-1-y = rows y+1, y */
                d = dst + (size_t)x * ds + (size_t)(h - 2u - y) * 2u;
                ST32(d, (b & 0xffffu) | (a << 16));
                ST32(d + ds, (b >> 16) | (a & 0xffff0000u));
            } else {
                /* dst row w-1-x-j, pair columns y, y+1 = rows y, y+1 */
                d = dst + (size_t)(w - 1u - x) * ds + (size_t)y * 2u;
                ST32(d, (a & 0xffffu) | (b << 16));
                ST32(d - ds, (a >> 16) | (b & 0xffff0000u));
            }
        }
    }
}
#endif /* NV12_ROT_WORDS */

static void rot180_plane(const uint8_t *src, uint32_t ss, uint8_t *dst,
                         uint32_t ds, uint32_t w, uint32_t h, int bpp,
                         int words)
{
    uint32_t y;

    for (y = 0; y < h; y++) {
        const uint8_t *s = src + (size_t)y * ss;
        uint8_t *d = dst + (size_t)(h - 1u - y) * ds;
        uint32_t x = 0;

#if NV12_ROT_WORDS
        if (words) {
            uint32_t step = bpp == 1 ? 4u : 2u;     /* samples per word */
            uint32_t full = w - w % step;

            for (; x < full; x += step) {
                uint32_t v = LD32(s + x * (uint32_t)bpp);

                v = bpp == 1 ? __builtin_bswap32(v) : (v >> 16) | (v << 16);
                ST32(d + (w - step - x) * (uint32_t)bpp, v);
            }
        }
#else
        (void)words;
#endif
        for (; x < w; x++) {
            if (bpp == 1) {
                d[w - 1u - x] = s[x];
            } else {
                d[(w - 1u - x) * 2u] = s[x * 2u];
                d[(w - 1u - x) * 2u + 1u] = s[x * 2u + 1u];
            }
        }
    }
}

/*
 * PREF 30 (PrepareForStore) for the C path: allocates a cache line without
 * reading it from memory. PREF is base MIPS32 (no COP2), so it is safe on
 * every XBurst core, T23 included; a core that does not implement the hint
 * treats it as a NOP. The old contents of the line become undefined, so it
 * is only issued on whole 32-byte lines that the code writes completely
 * right afterwards (an eviction in between costs time, not correctness).
 */
#if defined(__mips__)
#define NV12_C_PREF_STORE(p) __asm__ volatile("pref 30, 0(%0)" :: "r"(p))
#else
#define NV12_C_PREF_STORE(p) ((void)(p))
#endif

/* The cache line of every XBurst1 core (T10..T31): 32 bytes. */
#define NV12_ROT_LINE 32u

#if NV12_ROT_WORDS
/*
 * 16-bit 2x2 transpose of two words in place: lo = [lo.h0 hi.h0],
 * hi = [lo.h1 hi.h1] (h0 = bits 0..15). Three instructions on MIPS32R2
 * (SRL + 2x INS; GCC makes 7 of the C form). INS is base MIPS32R2, which
 * every libimp build already targets (-march=mips32r2).
 */
#if defined(__mips__) && defined(__mips_isa_rev) && __mips_isa_rev >= 2
#define NV12_PAIR16(lo, hi) do {                                        \
        uint32_t t_ = (lo) >> 16;                                       \
        __asm__("ins %0, %1, 16, 16" : "+r"(lo) : "r"(hi));             \
        __asm__("ins %0, %1, 0, 16" : "+r"(hi) : "r"(t_));              \
    } while (0)
#else
#define NV12_PAIR16(lo, hi) do {                                        \
        uint32_t t_ = (lo) >> 16;                                       \
        (lo) = ((lo) & 0xffffu) | ((hi) << 16);                         \
        (hi) = ((hi) & 0xffff0000u) | t_;                               \
    } while (0)
#endif

/*
 * 4x4 byte transpose in place, 18 operations (TRANSPOSE4: 28): rows a..d
 * (byte k = column k) become columns (byte k = row k: a, b, c, d). 16-bit
 * 2x2 first, then the byte 2x2 as a delta swap.
 */
#define NV12_T4(a, b, c, d) do {                                        \
        uint32_t u_;                                                    \
        NV12_PAIR16(a, c);                                              \
        NV12_PAIR16(b, d);                                              \
        u_ = (((a) >> 8) ^ (b)) & 0x00ff00ffu;                          \
        (b) ^= u_;                                                      \
        (a) ^= u_ << 8;                                                 \
        u_ = (((c) >> 8) ^ (d)) & 0x00ff00ffu;                          \
        (d) ^= u_;                                                      \
        (c) ^= u_ << 8;                                                 \
    } while (0)

/* Keeps the compiler from turning the unrolled band loops into one
 * precomputed pointer per source row (32 of them, spilled to the stack). */
#define NV12_ROT_OPAQUE(p) __asm__("" : "+r"(p))

/* C 90/270 kernel: 1 cache-line banded (default), 2 banded with one-line
 * bands whatever the alignment, 0 the plain 32x32 tiles (2 and 0 for tests
 * and benchmarks) */
static int nv12_rot_c_banded = 1;

/* PREF 30 on every whole cache line inside [l, l + bytes) of each of the
 * n destination rows: the caller writes all those bytes next. */
static inline __attribute__((always_inline)) void
pref_store_segs(uint8_t *const *l, int n, uint32_t bytes)
{
    int i;

    for (i = 0; i < n; i++) {
        uintptr_t a = (uintptr_t)l[i], p, e = a + bytes;

        if (bytes == NV12_ROT_LINE) {   /* the common case: one line */
            if ((a & (NV12_ROT_LINE - 1u)) == 0u)
                NV12_C_PREF_STORE(l[i]);
            continue;
        }
        p = (a + NV12_ROT_LINE - 1u) & ~(uintptr_t)(NV12_ROT_LINE - 1u);
        for (; p + NV12_ROT_LINE <= e; p += NV12_ROT_LINE)
            NV12_C_PREF_STORE((uint8_t *)p);
    }
}

/*
 * One luma band: source rows [y0, y0+n) (n a multiple of 4, at most 64)
 * become n contiguous bytes from destination column col of every
 * destination row. The walk goes along x in 4-column steps and, for each,
 * down the band: the four destination rows are written front to back, one
 * whole cache line each when n is 32 and the line is aligned (allocated
 * with PREF 30 first); the band's source lines stay in L1 across the 8
 * steps that read them.
 */
static inline __attribute__((always_inline)) void
rot90_y_band(const uint8_t *src, uint32_t ss, uint8_t *dst, uint32_t ds,
             uint32_t w, int cw, uint32_t y0, uint32_t n, size_t col)
{
    const uint8_t *s0 = src + (size_t)y0 * ss;
    const size_t ss4 = (size_t)ss * 4u;
    uint32_t x, k;

    for (x = 0; x < w; x += 4u) {
        const uint8_t *s = s0 + x;
        uint8_t *d[4];

        if (cw) {
            d[0] = dst + (size_t)x * ds + col;
            d[1] = d[0] + ds;
            d[2] = d[1] + ds;
            d[3] = d[2] + ds;
        } else {
            d[0] = dst + (size_t)(w - 1u - x) * ds + col;
            d[1] = d[0] - ds;
            d[2] = d[1] - ds;
            d[3] = d[2] - ds;
        }
        pref_store_segs(d, 4, n);
        if (cw) {
            /* rows y+3 .. y land at columns n-4-k .. n-1-k */
#pragma GCC unroll 8
            for (k = 0; k < n; k += 4u) {
                uint32_t r0 = LD32(s), r1 = LD32(s + ss);
                uint32_t r2 = LD32(s + 2u * ss), r3 = LD32(s + 3u * ss);

                s += ss4;
                NV12_ROT_OPAQUE(s);
                NV12_T4(r3, r2, r1, r0);
                ST32(d[0] + (n - 4u - k), r3);
                ST32(d[1] + (n - 4u - k), r2);
                ST32(d[2] + (n - 4u - k), r1);
                ST32(d[3] + (n - 4u - k), r0);
            }
        } else {
#pragma GCC unroll 8
            for (k = 0; k < n; k += 4u) {
                uint32_t r0 = LD32(s), r1 = LD32(s + ss);
                uint32_t r2 = LD32(s + 2u * ss), r3 = LD32(s + 3u * ss);

                s += ss4;
                NV12_ROT_OPAQUE(s);
                NV12_T4(r0, r1, r2, r3);
                ST32(d[0] + k, r0);
                ST32(d[1] + k, r1);
                ST32(d[2] + k, r2);
                ST32(d[3] + k, r3);
            }
        }
    }
}

/* One CbCr band: n pair rows (even, at most 32), 2 pairs per step. */
static inline __attribute__((always_inline)) void
rot90_uv_band(const uint8_t *src, uint32_t ss, uint8_t *dst, uint32_t ds,
              uint32_t w, int cw, uint32_t y0, uint32_t n, size_t col)
{
    const uint8_t *s0 = src + (size_t)y0 * ss;
    const size_t ss2 = (size_t)ss * 2u;
    uint32_t x, k;

    for (x = 0; x < w; x += 2u) {
        const uint8_t *s = s0 + (size_t)x * 2u;
        uint8_t *d[2];

        if (cw) {
            d[0] = dst + (size_t)x * ds + col;
            d[1] = d[0] + ds;
        } else {
            d[0] = dst + (size_t)(w - 1u - x) * ds + col;
            d[1] = d[0] - ds;
        }
        pref_store_segs(d, 2, n * 2u);
        if (cw) {
            /* pair columns n-2-k, n-1-k = rows y+1, y */
#pragma GCC unroll 8
            for (k = 0; k < n; k += 2u) {
                uint32_t a = LD32(s), b = LD32(s + ss);

                s += ss2;
                NV12_ROT_OPAQUE(s);
                NV12_PAIR16(b, a);
                ST32(d[0] + (n - 2u - k) * 2u, b);
                ST32(d[1] + (n - 2u - k) * 2u, a);
            }
        } else {
#pragma GCC unroll 8
            for (k = 0; k < n; k += 2u) {
                uint32_t a = LD32(s), b = LD32(s + ss);

                s += ss2;
                NV12_ROT_OPAQUE(s);
                NV12_PAIR16(a, b);
                ST32(d[0] + k * 2u, a);
                ST32(d[1] + k * 2u, b);
            }
        }
    }
}

/*
 * 90/270 word path over the whole plane, cache-line banded (both sides in
 * whole 4x4 / 2x2 blocks, buffers word-aligned).
 *
 * Measured on T23 (no MXU, 2026-11-06, nv12_rotate_bench and a luma
 * micro benchmark, 704x576): the 32x32-tile path took 2.4 ms for the luma
 * plane, of which ~1.0 ms were the transposes alone (data in L1), ~0.7 ms
 * the tile loads and ~1.1 ms the scattered 4-byte stores (each tile touches
 * 32 destination lines 8 times); a memcpy of the same bytes takes 0.47 ms.
 * PREF 0 on the source made it slower. Hence:
 *  - a band is the source rows that fill one destination cache line (32
 *    luma rows, 16 CbCr pair rows), anchored at destination column 0 (CW:
 *    at the source bottom, CCW: at the top; the remainder band at the
 *    other end), so a full band writes whole aligned lines;
 *  - each destination line is allocated with PREF 30 and written front to
 *    back in one go (rot90_*_band);
 *  - the 4x4 transpose takes 18 instead of 28 operations (NV12_T4).
 */
static void rot90_words_banded(const uint8_t *src, uint32_t ss, uint8_t *dst,
                               uint32_t ds, uint32_t w, uint32_t h, int bpp,
                               int mode)
{
    const int cw = mode == NV12_ROT_90_CW;
    /* destination bytes per band row: one line; two for CW when the
     * destination rows are not line-aligned (a 16-byte offset then leaves
     * one whole line per band row instead of none). T23N, nv12_rotate_bench
     * 2026-11-06: CW 640x368 1.74 vs 1.94 ms, 1280x720 8.56 vs 8.73 ms;
     * CCW is faster with one line (1.69 vs 1.77, 7.94 vs 8.47 ms). */
    const uint32_t bb = nv12_rot_c_banded == 1 && cw &&
                        (((uintptr_t)dst | ds) & (NV12_ROT_LINE - 1u)) ?
                        2u * NV12_ROT_LINE : NV12_ROT_LINE;
    const uint32_t band = bb / (uint32_t)bpp;     /* source rows per band */
    const uint32_t rem = h % band;
    uint32_t y0, y1;

    for (y0 = 0; y0 < h; y0 = y1) {
        size_t col;

        if (cw)
            y1 = y0 == 0 && rem ? rem : y0 + band;
        else
            y1 = y0 + band <= h ? y0 + band : h;
        /* destination byte column of the band's first byte */
        col = (size_t)(cw ? h - y1 : y0) * (uint32_t)bpp;
        if (bpp == 1) {
            if (y1 - y0 == 32u)
                rot90_y_band(src, ss, dst, ds, w, cw, y0, 32u, col);
            else if (y1 - y0 == 64u)
                rot90_y_band(src, ss, dst, ds, w, cw, y0, 64u, col);
            else
                rot90_y_band(src, ss, dst, ds, w, cw, y0, y1 - y0, col);
        } else {
            if (y1 - y0 == 16u)
                rot90_uv_band(src, ss, dst, ds, w, cw, y0, 16u, col);
            else if (y1 - y0 == 32u)
                rot90_uv_band(src, ss, dst, ds, w, cw, y0, 32u, col);
            else
                rot90_uv_band(src, ss, dst, ds, w, cw, y0, y1 - y0, col);
        }
    }
}
#endif /* NV12_ROT_WORDS */

/* C rotation of the rectangle [x0,x1) x [y0,y1) (90/270 only): word path
 * in 32x32 tiles when the plane allows it, scalar otherwise. */
static void rot90_c_rect(const uint8_t *src, uint32_t ss, uint8_t *dst,
                         uint32_t ds, uint32_t w, uint32_t h, int bpp,
                         int mode, int words, uint32_t x0, uint32_t x1,
                         uint32_t y0, uint32_t y1)
{
    uint32_t tx, ty;

    if (x0 >= x1 || y0 >= y1)
        return;
    if (!words) {
        rot_scalar(src, ss, dst, ds, w, h, bpp, mode, x0, x1, y0, y1);
        return;
    }
    for (ty = y0; ty < y1; ty += NV12_ROT_TILE) {
        uint32_t ye = ty + NV12_ROT_TILE < y1 ? ty + NV12_ROT_TILE : y1;

        for (tx = x0; tx < x1; tx += NV12_ROT_TILE) {
            uint32_t xe = tx + NV12_ROT_TILE < x1 ? tx + NV12_ROT_TILE : x1;

#if NV12_ROT_WORDS
            if (bpp == 1)
                rot90_y_words(src, ss, dst, ds, w, h, mode, tx, xe, ty, ye);
            else
                rot90_uv_words(src, ss, dst, ds, w, h, mode, tx, xe, ty, ye);
#else
            rot_scalar(src, ss, dst, ds, w, h, bpp, mode, tx, xe, ty, ye);
#endif
        }
    }
}

